// The site command builds a static site from the product catalog.
package main

import (
	"bytes"
	"embed"
	"flag"
	"fmt"
	"html/template"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/toshicloud/toshi-catalog/internal/catalog"
)

//go:embed templates/*.html style.css
var assets embed.FS

const generatedHeader = "<!-- Generated by the Toshi catalog site. -->\n"

type productView struct {
	catalog.Product
	PublisherName string
	LatestVersion *catalog.Version
	GoGet         string
	HostedModule  string
	HostedVersion string
	Hosted        bool
}

type pageHeader struct {
	Title string
	Root  string
}

type indexPage struct {
	pageHeader
	Products []productView
}

type productPage struct {
	pageHeader
	Product productView
}

type manifestPart struct {
	Text           string
	CarriageReturn bool
}

type hostedPage struct {
	pageHeader
	Builtins []string
	Products []productView
	Manifest []manifestPart
}

type outputFile struct {
	name string
	data []byte
}

func main() { os.Exit(run(os.Args[1:], os.Stdout, os.Stderr)) }

func run(args []string, stdout, stderr io.Writer) int {
	flags := flag.NewFlagSet("site", flag.ContinueOnError)
	flags.SetOutput(io.Discard)
	dir := flags.String("dir", ".", "catalog directory")
	out := flags.String("out", "", "output directory")
	if err := flags.Parse(args); err != nil {
		fmt.Fprintf(stderr, "site: flags: %v\n", err)
		return 1
	}
	if flags.NArg() != 0 {
		fmt.Fprintf(stderr, "site: flags: unexpected arguments: %s\n", strings.Join(flags.Args(), " "))
		return 1
	}
	if *out == "" {
		fmt.Fprintln(stderr, "site: flags: -out is required")
		return 1
	}

	c, problems, err := catalog.Load(*dir)
	for _, problem := range problems {
		fmt.Fprintln(stderr, problem.String())
	}
	if err != nil {
		fmt.Fprintf(stderr, "site: %v\n", err)
		return 1
	}
	if len(problems) != 0 {
		return 1
	}

	files, err := build(c, *dir)
	if err == nil {
		err = writeFiles(*out, files)
	}
	if err != nil {
		fmt.Fprintf(stderr, "site: %v\n", err)
		return 1
	}
	for _, file := range files {
		if _, err := fmt.Fprintln(stdout, file.name); err != nil {
			fmt.Fprintf(stderr, "site: output: %v\n", err)
			return 1
		}
	}
	return 0
}

// build renders all pages before writing, using only the canonical hosted manifest.
func build(c *catalog.Catalog, dir string) ([]outputFile, error) {
	var distribution *catalog.Distribution
	for i := range c.Distributions {
		if c.Distributions[i].File == "distributions/hosted.toml" {
			distribution = &c.Distributions[i]
			break
		}
	}
	if distribution == nil || distribution.Name != "hosted" {
		return nil, fmt.Errorf("distributions/hosted.toml must name the hosted distribution")
	}
	manifest, err := os.ReadFile(filepath.Join(dir, "distributions", "hosted.toml"))
	if err != nil {
		return nil, fmt.Errorf("read hosted distribution: %w", err)
	}
	templates, err := template.ParseFS(assets, "templates/*.html")
	if err != nil {
		return nil, fmt.Errorf("parse templates: %w", err)
	}

	publishers := make(map[string]string, len(c.Publishers))
	for _, publisher := range c.Publishers {
		publishers[publisher.ID] = publisher.Name
	}
	products := make([]productView, 0, len(c.Products))
	for i := range c.Products {
		p := &c.Products[i]
		module, version, hosted := c.Hosted(p.ID)
		view := productView{
			Product: *p, PublisherName: publishers[p.Publisher], LatestVersion: p.Latest(),
			HostedModule: module, HostedVersion: version, Hosted: hosted,
		}
		if view.LatestVersion != nil && !p.IsWithdrawn() {
			view.GoGet = "go get " + p.Module + "@" + view.LatestVersion.Version
		}
		products = append(products, view)
	}

	hosted := hostedPage{pageHeader: pageHeader{Title: "Hosted", Root: ""}}
	// Literal carriage returns in HTML are normalized by browsers; character
	// references preserve the manifest's original line endings when copied.
	parts := strings.Split(string(manifest), "\r")
	for i, part := range parts {
		hosted.Manifest = append(hosted.Manifest, manifestPart{Text: part, CarriageReturn: i < len(parts)-1})
	}
	for _, product := range distribution.Products {
		if product.Builtin != nil && *product.Builtin {
			hosted.Builtins = append(hosted.Builtins, product.ID)
		}
	}
	for _, product := range products {
		if product.Hosted {
			hosted.Products = append(hosted.Products, product)
		}
	}

	var files []outputFile
	render := func(name, page string, data interface{}) error {
		var buf bytes.Buffer
		buf.WriteString(generatedHeader)
		if err := templates.ExecuteTemplate(&buf, page, data); err != nil {
			return fmt.Errorf("render %s: %w", name, err)
		}
		files = append(files, outputFile{name, buf.Bytes()})
		return nil
	}
	if err := render("index.html", "index", indexPage{pageHeader{Title: "Products"}, products}); err != nil {
		return nil, err
	}
	for _, product := range products {
		page := productPage{pageHeader{Title: product.Name, Root: "../"}, product}
		if err := render("products/"+product.ID+".html", "product", page); err != nil {
			return nil, err
		}
	}
	if err := render("hosted.html", "hosted", hosted); err != nil {
		return nil, err
	}
	css, err := assets.ReadFile("style.css")
	if err != nil {
		return nil, fmt.Errorf("read stylesheet: %w", err)
	}
	return append(files, outputFile{"style.css", css}), nil
}

func writeFiles(out string, files []outputFile) error {
	productsDir := filepath.Join(out, "products")
	if err := os.MkdirAll(productsDir, 0o755); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}
	keep := make(map[string]bool)
	for _, file := range files {
		path := filepath.Join(out, filepath.FromSlash(file.name))
		if err := os.WriteFile(path, file.data, 0o644); err != nil {
			return fmt.Errorf("write %s: %w", file.name, err)
		}
		if strings.HasPrefix(file.name, "products/") {
			keep[filepath.Base(path)] = true
		}
	}
	// Remove only pages generated by a previous build, leaving other files alone.
	entries, err := os.ReadDir(productsDir)
	if err != nil {
		return fmt.Errorf("read product output directory: %w", err)
	}
	for _, entry := range entries {
		if !entry.Type().IsRegular() || !strings.HasSuffix(entry.Name(), ".html") || keep[entry.Name()] {
			continue
		}
		path := filepath.Join(productsDir, entry.Name())
		f, err := os.Open(path)
		if err != nil {
			return fmt.Errorf("read %s: %w", entry.Name(), err)
		}
		header := make([]byte, len(generatedHeader))
		_, readErr := io.ReadFull(f, header)
		closeErr := f.Close()
		if readErr != nil && readErr != io.EOF && readErr != io.ErrUnexpectedEOF {
			return fmt.Errorf("read %s: %w", entry.Name(), readErr)
		}
		if closeErr != nil {
			return fmt.Errorf("close %s: %w", entry.Name(), closeErr)
		}
		if string(header) == generatedHeader {
			if err := os.Remove(path); err != nil {
				return fmt.Errorf("remove stale page %s: %w", entry.Name(), err)
			}
		}
	}
	return nil
}
